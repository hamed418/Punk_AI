export type CampaignType =
  | 'Awareness'
  | 'Traffic'
  | 'Engagement'
  | 'LeadGeneration'
  | 'AppPromotion'
  | 'SalesConversion';

export type CampaignStatus = 'Active' | 'Paused' | 'Completed';

export type CampaignSource = 'PunkAI' | 'Other';

export interface TrendPoint {
  date: string;
  [metricKey: string]: number | string | null;
}

export interface BarPoint {
  label: string;
  value: number;
}

export interface GroupedBarPoint {
  label: string;
  [groupKey: string]: number | string;
}

export interface CardStat {
  label: string;
  value: string;
}

export interface TrendChartConfig {
  title: string;
  dataKey: string;
  section: 1 | 2 | 'overflow';
}

export interface ComparisonChartConfig {
  title: string;
  type: 'multiLine' | 'verticalBar' | 'horizontalBar' | 'groupedBar';
  source: 'trend' | string;
  dataKeys?: string[];
  section: 3 | 4 | 'overflow';
}

export type AdType = 'video' | 'image' | 'carousel' | 'collection' | 'dynamic';

export interface CampaignChartConfig {
  trend: TrendChartConfig[];
  comparison: ComparisonChartConfig[];
}

export interface CampaignBreakdown {
  videoRetention?: BarPoint[];
  frequencyDistribution?: BarPoint[];
  trafficJourney?: BarPoint[];
  engagementBreakdown?: BarPoint[];
  leadJourney?: BarPoint[];
  installJourney?: BarPoint[];
  conversionJourney?: BarPoint[];
  weeklyFunnelComparison?: GroupedBarPoint[];
}

export interface Campaign {
  id: string;
  campaignType: CampaignType;
  adType: AdType;
  objective: string;
  campaignId: string;
  title: string;
  subtitle: string;
  dateRange: string;
  status: CampaignStatus;
  currency: string;
  isFromPunkAI: boolean;
  source: CampaignSource;
  heroStat: CardStat;
  secondaryStat: CardStat;
  cardStats: CardStat[];
  trend: TrendPoint[];
  breakdown: CampaignBreakdown;
  charts: CampaignChartConfig;
  rawSample: Record<string, unknown>;
}

